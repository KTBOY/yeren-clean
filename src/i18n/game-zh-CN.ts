const escapeRegExp = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

// Word-boundary-guarded so short keys (No, Camp, stage…) never match inside longer words like "Not".
const PHRASES = Object.entries(DICTIONARY)
  .sort(([a], [b]) => b.length - a.length)
  .map(([source, target]) => {
    const lead = /^\w/.test(source) ? '\\b' : ''
    const trail = /\w$/.test(source) ? '\\b' : ''
    return [new RegExp(`${lead}${escapeRegExp(source)}${trail}`, 'g'), target] as const
  })

/** Translate visible English phrases without touching internal IDs or markup attributes such as data-act. */
export function zh(value: string): string {
  const trimmed = value.trim()
  const exact = DICTIONARY[trimmed]
  if (exact) return value.replace(trimmed, exact)
  let out = value
  for (const [pattern, target] of PHRASES) out = out.replace(pattern, target)
  out = out.replace(/\bObjective (\d+) \/ (\d+)\b/g, '目标 $1／$2')
  out = out.replace(/\bCamp stage (\d+) of 3\b/g, '营地阶段 $1／共 3 阶段')
  out = out.replace(/\bCamp stage ([IVX]+) of III\b/g, '营地阶段 $1／共 III 阶段')
  out = out.replace(/\bCamp ([IVX]+)\b/g, '营地 $1')
  out = out.replace(/\bCarve \((\d+) left\)/g, '剥取（剩余 $1 次）')
  out = out.replace(/\bStudy \((\d+)\/(\d+)\)/g, '调查（$1/$2）')
  out = out.replace(/\b(\d+) m\b/g, '$1 米')
  return out
}

/** Translate text nodes and human-readable attributes in internally authored markup. */
export function translateMarkup(markup: string): string {
  const template = document.createElement('template')
  template.innerHTML = markup
  const walker = document.createTreeWalker(template.content, NodeFilter.SHOW_TEXT)
  let node = walker.nextNode()
  while (node) {
    node.textContent = zh(node.textContent ?? '')
    node = walker.nextNode()
  }
  for (const element of template.content.querySelectorAll<HTMLElement>('*')) {
    for (const attr of ['title', 'aria-label', 'placeholder'] as const) {
      const value = element.getAttribute(attr)
      if (value) element.setAttribute(attr, zh(value))
    }
  }
  return template.innerHTML
}
